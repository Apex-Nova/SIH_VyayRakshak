export function resolve(locale: Locale, key: string): string {
  const parts = key.split(".");
  let node: string | Tree | undefined = dict[locale];
  for (const p of parts) {
    if (node && typeof node === "object") node = node[p];
    else return key;
  }
  if (typeof node === "string") return node;
  // Fallback to English before leaking the raw key.
  let en: string | Tree | undefined = dict.en;
  for (const p of parts) {
    if (en && typeof en === "object") en = en[p];
    else return key;
  }
  return typeof en === "string" ? en : key;
}
